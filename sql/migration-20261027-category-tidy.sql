-- ============================================================
-- 分类体系整理：树洞 / 闲置 / 频道 三个模块去重、划清边界
-- 执行库：guizhou_campus_fun
-- 幂等：MySQL 没有 ADD COLUMN IF NOT EXISTS，重复执行报 duplicate column 可忽略
-- 回退：本脚本不删任何业务数据（频道只置 status=0），恢复见文件末尾
-- ============================================================
--
-- 整理原则：一个模块只回答一个问题，模块之间不抢活。
--
--   树洞  = 我现在什么心情 / 需要什么帮忙   → 心情 / 吐槽 / 求助
--   闲置  = 我在卖什么品类的东西           → 数码 / 图书 / 生活 / 服饰 / 运动 / 代步 / 其他
--   频道  = 大家在一起聊什么公共话题        → 校园公告 / 吃喝玩乐 / 运动搭子
--
-- 本次解决的三处重复：
--   ① 频道 2004「树洞吐槽」抢树洞模块主场        → 下线
--   ② 频道 2005「二手交易」抢闲置模块主场        → 下线
--   ③ 树洞 find / findp「寻物」「寻人」拆成两个   → 前端合并为「求助」，存量值不动
--
-- 注意：频道用 status 软下线而不是 DELETE。
--   t_post.channel_id 有存量引用，直接删行会让历史帖子的频道名丢失；
--   软下线后 GET /channels 不返回，但帖子详情仍能按 id 查到频道名。
-- ------------------------------------------------------------

-- ------------------------------------------------------------
-- 1. 频道表加上下线开关
-- ------------------------------------------------------------
ALTER TABLE t_channel ADD COLUMN status TINYINT NOT NULL DEFAULT 1 COMMENT '1上线 0下线(不返回给小程序，存量帖子仍可解析频道名)' AFTER post_count;

-- ------------------------------------------------------------
-- 2. 下线两个抢别的模块主场的频道
--    2004 树洞吐槽 → 树洞模块（pages/wall/index）已经独占「吐槽」这个场景
--    2005 二手交易 → 闲置模块（pages/goods/list）有完整的品类、成色、面交、搜索热词
--    留着它们的后果：用户在同一件事上有两个发布入口，内容被劈成两半，
--    而且频道里的闲置不走闲置模块的搜索/推广/品类筛选。
-- ------------------------------------------------------------
UPDATE t_channel SET status = 0 WHERE id IN (2004, 2005);

-- ------------------------------------------------------------
-- 3. 「校园公告」描述明确边界：把失物招领归到这里
--    树洞的「求助」管的是找人倾诉式的寻物，公告频道管的是正式挂出的招领
-- ------------------------------------------------------------
UPDATE t_channel SET description = '失物招领 · 校园通知 · 社团招新' WHERE id = 2001;

-- ------------------------------------------------------------
-- 4. 闲置品类补「代步」，放在「运动」之后、「其他」之前
--    商品分类 id 不能重排（存量 t_goods.category_id 已落库），
--    所以新品类只能往后追加 id=7，展示顺序由后端 CATEGORIES 列表顺序决定，
--    不受 id 大小影响。
--    校园二手的高频品：自行车/电动车/滑板，原来只能塞进「运动」或「其他」。
-- ------------------------------------------------------------
ALTER TABLE t_goods MODIFY COLUMN category_id INT NOT NULL DEFAULT 0
  COMMENT '1数码 2图书 3生活 4服饰 5运动 6其他 7代步';

-- ------------------------------------------------------------
-- 5. 树洞分类字段注释同步（值不变，只是把语义写清楚）
--    存量数据 find / findp 保持原值，前端把两者合并展示为「求助」，
--    后端 category 参数支持逗号分隔多值（category=find,findp）。
-- ------------------------------------------------------------
ALTER TABLE t_wall_post MODIFY COLUMN category VARCHAR(16) NOT NULL DEFAULT 'love'
  COMMENT '分类：love心情/tree吐槽/find寻物/findp寻人(前端合并为一个「求助」tab)';

