-- 群名统一为「校友群」（2026-10-27）
--
-- 背景：原群名 = {学校名} + 校友群（如「贵州铜仁数据职业学院校友群」）。
--   群聊页是自绘单行顶栏 + 右侧「群设置」入口，长校名会把标题挤成
--   「贵州铜仁数据职业学院...」—— 学校名看不全，真正的群名「校友群」反而被截掉。
--
-- 决策：群名固定「校友群」，学校身份由群设置页副标题（N 位校友 · {学校名}）承载。
--   新建群代码侧已改：GroupJoinService.GROUP_NAME；本脚本处理历史数据。
--
-- 幂等：只改 type=1 且名字不是「校友群」的行，可重复执行。

UPDATE `t_group`
   SET `name` = '校友群'
 WHERE `type` = 1
   AND `name` <> '校友群';

